import { useDocumentStore } from "@features/document/store/document-store";
import { CONTEXT_PROMPT_MARKER } from "@features/agent/message";
import { FLOWIX_EMBED_HTML_PROMPT_BLOCK } from "@features/agent/embed-html-prompt";
